"""Generate docs/SETTINGS.md from the SETTINGS dict in inventree_xero/core.py (no InvenTree needed).

    python tools/gen_settings_doc.py          # rewrite docs/SETTINGS.md
    python tools/gen_settings_doc.py --check  # exit 1 if docs/SETTINGS.md is out of date (CI)
"""

import ast
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
CORE = ROOT / 'inventree_xero' / 'core.py'
OUT = ROOT / 'docs' / 'SETTINGS.md'


def literal(node):
    try:
        return ast.literal_eval(node)
    except (ValueError, SyntaxError):
        return None


def load_settings():
    tree = ast.parse(CORE.read_text(encoding='utf-8'))
    groups, current = [], None
    source = CORE.read_text(encoding='utf-8').splitlines()
    for node in ast.walk(tree):
        if isinstance(node, ast.Assign) and any(getattr(t, 'id', None) == 'SETTINGS' for t in node.targets):
            settings_node = node.value
            break
    else:
        raise SystemExit('SETTINGS not found in core.py')

    # group headings come from the "# ---- name" comments inside the dict
    headings = {}
    for lineno, text in enumerate(source, start=1):
        stripped = text.strip()
        if stripped.startswith('# ----') and settings_node.lineno <= lineno <= settings_node.end_lineno:
            headings[lineno] = stripped.strip('# -').strip()

    for key_node, value_node in zip(settings_node.keys, settings_node.values):
        heading = max((ln for ln in headings if ln < key_node.lineno), default=None)
        group = headings.get(heading, 'General')
        if current is None or current[0] != group:
            current = (group, [])
            groups.append(current)
        entry = {'key': literal(key_node)}
        for k, v in zip(value_node.keys, value_node.values):
            name = literal(k)
            if name in ('name', 'description', 'default', 'choices'):
                entry[name] = literal(v)
            elif name == 'validator':
                entry['type'] = 'yes / no' if getattr(v, 'id', None) == 'bool' else 'number'
            elif name == 'protected':
                entry['protected'] = True
        current[1].append(entry)
    return groups


def fmt_default(entry):
    default = entry.get('default')
    if entry.get('choices'):
        labels = dict(entry['choices'])
        return labels.get(default, default)
    if isinstance(default, bool):
        return 'yes' if default else 'no'
    if default in ('', None):
        return '(blank)'
    return f'`{default}`'


def render(groups):
    lines = [
        '# Settings reference',
        '',
        '<!-- Generated by tools/gen_settings_doc.py from inventree_xero/core.py - do not edit by hand. -->',
        '',
        'All settings are on the plugin\'s settings page in InvenTree (Admin Center → Plugins → Xero). '
        'Defaults are the safe choice unless noted.',
        '',
    ]
    for group, entries in groups:
        lines += [f'## {group.capitalize()}', '', '| Setting | Key | Default | What it does |', '|---|---|---|---|']
        for e in entries:
            desc = (e.get('description') or '').replace('|', '\\|').rstrip()
            if desc and desc[-1] not in '.)':
                desc += '.'
            if e.get('choices'):
                desc += ' Options: ' + '; '.join(label for _, label in e['choices']) + '.'
            if e.get('protected'):
                desc += ' (Stored protected.)'
            lines.append(f"| {e.get('name')} | `{e['key']}` | {fmt_default(e)} | {desc} |")
        lines.append('')
    return '\n'.join(lines)


def main():
    text = render(load_settings())
    if '--check' in sys.argv:
        if not OUT.exists() or OUT.read_text(encoding='utf-8') != text:
            print('docs/SETTINGS.md is out of date - run python tools/gen_settings_doc.py')
            raise SystemExit(1)
        print('docs/SETTINGS.md is up to date')
        return
    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text(text, encoding='utf-8', newline='\n')
    print(f'wrote {OUT.relative_to(ROOT)}')


if __name__ == '__main__':
    main()
